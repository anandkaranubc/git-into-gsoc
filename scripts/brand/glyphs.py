def glyph(ch: str) -> Glyph:
    key = ch.lower() if ch.lower() in GLYPHS else ch
    return GLYPHS.get(key, GLYPHS["?"])


def glyph_width(ch: str) -> int:
    return max(len(r) for r in glyph(ch)[1])


def text(s: str, x0: int = 0, baseline: int = 0, track: int = TRACK) -> tuple[Cells, int]:
    """Lay out ``s`` on the grid. ``baseline`` is the y of row 0 (top of the x-height).

    Returns the cells and the advance width in cells.
    """
    cells: Cells = set()
    x = x0
    for ch in s:
        if ch == " ":
            x += SPACE
            continue
        top, rows = glyph(ch)
        cells |= parse(rows, x, baseline + top)
        x += glyph_width(ch) + track
    return cells, x - track - x0


def text_width(s: str, track: int = TRACK) -> int:
    return text(s, track=track)[1]


def icon(name: str, x0: int = 0, y0: int = 0) -> Cells:
    return parse(ICONS[name], x0, y0)
